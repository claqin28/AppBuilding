// Generates src/viz/canonicalFace.ts from MediaPipe's canonical face model.
//
// Source: mediapipe/modules/face_geometry/data/canonical_face_model.obj in
// https://github.com/google-ai-edge/mediapipe (Apache-2.0, (c) The MediaPipe Authors).
// The model's 468 vertices are numbered the same way as Face Landmarker's
// landmarks 0-467 (checked 2026-10-22, see DECISIONS.md).
//
// Usage: node scripts/make-canonical-face.mjs path/to/canonical_face_model.obj
import { readFileSync, writeFileSync } from "node:fs";

const [, , objPath] = process.argv;
if (!objPath) throw new Error("Pass the path to canonical_face_model.obj");
const verts = readFileSync(objPath, "utf8")
  .split("\n")
  .filter((l) => l.startsWith("v "))
  .map((l) => l.slice(2).trim().split(/\s+/).map(Number));
if (verts.length !== 468) throw new Error(`Expected 468 vertices, got ${verts.length}`);
const flat = verts.flat().map((x) => Math.round(x * 1000) / 1000);

const out = `// GENERATED by scripts/make-canonical-face.mjs. Do not edit by hand.
//
// MediaPipe's canonical ("standard") face: 468 points in centimetres.
// +x = the person's own left, +y = up, +z = toward the viewer.
// Point i matches Face Landmarker landmark i.
//
// Source: mediapipe/modules/face_geometry/data/canonical_face_model.obj,
// https://github.com/google-ai-edge/mediapipe
// Copyright The MediaPipe Authors. Licensed under the Apache License 2.0.

/** x, y, z for each of the 468 points, flattened. */
export const CANONICAL_FACE: readonly number[] = [${flat.join(",")}];

export const CANONICAL_POINT_COUNT = 468;
`;
writeFileSync("src/viz/canonicalFace.ts", out);
console.log(`wrote src/viz/canonicalFace.ts (${verts.length} points)`);
